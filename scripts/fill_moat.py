AUTO_NONE = "{biz}——行业内充分竞争，未见牌照、配额、独家资源或技术独占"


def code_of(symbol: str) -> str:
    return symbol[:2].upper() + symbol[2:]


def main() -> int:
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    have = {r[0] for r in conn.execute(
        "select symbol from annotation where kind='moat'")}
    stocks = conn.execute(
        "select symbol,name,industry,business from stock order by symbol").fetchall()

    unknown = set(MOAT) - {r["symbol"] for r in stocks}
    if unknown:
        raise SystemExit(f"MOAT 里有 stock 表没有的代码：{sorted(unknown)}")

    added = {"moat": 0, "none": 0}
    for r in stocks:
        sym = r["symbol"]
        if sym in have:
            continue
        if sym in MOAT:
            mt, ev = MOAT[sym]
            added["moat"] += 1
        else:
            biz = (r["business"] or "").strip().rstrip("。；")
            biz = (biz[:60] + "…") if len(biz) > 60 else biz
            mt = "无标注"
            ev = AUTO_NONE.format(biz=biz) if biz else "行业内充分竞争，未见垄断性资源"
            added["none"] += 1
        A.put(conn, sym, moat_type=mt, evidence=ev,
              sources=[F10.format(code=code_of(sym))],
              verified=VERIFIED, note=NOTE)
    conn.commit()

    total = conn.execute(
        "select count(*) from annotation where kind='moat'").fetchone()[0]
    dist = conn.execute(
        "select moat_type, count(*) from annotation where kind='moat' "
        "group by moat_type order by 2 desc").fetchall()
    print(f"新增：有垄断 {added['moat']} 只，无标注 {added['none']} 只")
    print(f"annotation 总计 {total} 条 / stock 表 {len(stocks)} 只")
    for k, v in dist:
        print(f"  {k:6s} {v}")
    conn.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
