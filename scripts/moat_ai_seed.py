def main() -> int:
    ap = argparse.ArgumentParser(description="AI 种子名单补 moat_type")
    ap.add_argument("--db", default=str(DB))
    ap.add_argument("--day", default="2026-11-16")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true", help="连非「无标注」的也覆盖")
    a = ap.parse_args()

    conn = sqlite3.connect(a.db)
    conn.row_factory = sqlite3.Row

    names = list(SEED)
    rows = conn.execute(
        f"select s.symbol, s.name, an.moat_type from stock s left join annotation an "
        f"on an.symbol=s.symbol and an.kind='moat' "
        f"where s.name in ({','.join('?' * len(names))})", names).fetchall()
    found = {r["name"]: r for r in rows}
    missing = [n for n in names if n not in found]

    # 补按代码给的几条
    for sym, (mtype, why) in SEED_BY_CODE.items():
        r = conn.execute(
            "select s.symbol, s.name, an.moat_type from stock s "
            "left join annotation an on an.symbol=s.symbol and an.kind='moat' "
            "where s.symbol=?", (sym,)).fetchone()
        if r:
            found[r["name"] or sym] = r
            SEED.setdefault(r["name"] or sym, (mtype, why))
        else:
            missing.append(sym)

    todo = []
    for name, r in found.items():
        cur = r["moat_type"]
        if cur and cur != "无标注" and not a.force:
            continue
        todo.append((r["symbol"], name, cur, *SEED[name]))

    print(f"种子 {len(SEED)} 只｜库中匹配 {len(found)}｜将写入 {len(todo)}"
          + ("（dry-run）" if a.dry_run else ""))
    if missing:
        print(f"库中未匹配 {len(missing)} 只（名称不一致，需人工对代码）：{missing}")
    for sym, name, cur, mtype, why in todo[:10]:
        print(f"  {sym} {name:6s} {cur or '—':5s} → {mtype:5s} {why}")

    if not a.dry_run:
        for sym, name, cur, mtype, why in todo:
            A.put(conn, sym, moat_type=mtype, evidence=why,
                  verified=a.day, note=NOTE.format(day=a.day))
        conn.commit()
        print("\n写入后：")
        for k, v in conn.execute(
                "select moat_type,count(*) from annotation where kind='moat' "
                "group by 1 order by 2 desc"):
            print(f"  {k:6s} {v}")
    conn.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
