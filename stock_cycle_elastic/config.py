# ---------------------------------------------------------------------------
# 3. 判定阈值（README.md 的判定阈值）—— 只有 11 个
# ---------------------------------------------------------------------------
# 这 11 个是全部"做判断"用的数字。test_config_contract.py 会断言数量恰好为 11。
#
# 判断① 为什么从 1 个阈值变成 4 个：
#   绝对标准差（pp）是把有量纲的尺子。毛利率水平只有十几个点的公司，
#   σ 在数学上就到不了 5pp —— 实测毛利率中位 < 10% 的 17 只里只有 35% 能过线，
#   而 ≥10% 的组是 49%。同一把尺子，低毛利公司天然吃亏（详见
#   《判断①漏判周期股的改进建议-20261113.md》）。
#   补一条**相对波动**通道后，低毛利组命中率回到 89%，两组的待遇才拉平。

#: 判断① 通道 A（绝对）：毛利率 5 年标准差 >= 此值 → 判为周期股。
#: 依据：东北证券《因子研究第七期》毛利率 5 年窗口标准差 > 5pp。
#: 注意：文献口径是年度/滚动值，本工具用季度单季值，通常会略高（季节性）。
#: 校准记录（--stats 抽样，目标命中率 20-40%）：待 P7 阶段回填。
GM_STD_CYCLE = 5.0

#: 判断① 通道 B（相对）：变异系数 CV = σ / |毛利率中位| >= 此值（%）→ 判为周期股。
#: 含义：毛利率波动的相对幅度。低毛利生意（十几点的毛利率）波动 3-4pp
#: 已经是 25-35% 的相对摆动，跟高毛利生意波动 10pp 是一回事。
#: 标定：113 只实测，CV≥20% 时低毛利组命中率 89%、高毛利组 58%（绝对口径是 35%/49%）。
GM_CV_MIN = 20.0

#: 判断① 通道 B 的守卫 1：毛利率中位数 >= 此值（%）才允许用 CV 通道。
#: 为什么必须要有：中位数接近 0 时 CV 的分母趋零，比值会爆炸成几百（实测
#: 振华新材中位 −3.8% → CV=354%）。这是防脏数据的守卫，不是"多一条标准"。
GM_MEDIAN_MIN = 5.0

#: 判断① 通道 B 的守卫 2：绝对 σ >= 此值（pp）才允许用 CV 通道。
#: 为什么还要留一条绝对下限：CV 高但绝对波动极小的公司（如纯冶炼加工，
#: 毛利率 2-6% 之间晃），波动的是加工费而不是价差，用毛利率量它本来就是
#: 选错了指标 —— 不该靠 CV 通道把它放进来。
GM_STD_MIN_FOR_CV = 2.0

#: 判断②：营业利润增速/营收增速 的中位数 >= 此值 → 弹性强。
#: 依据：DOL 常用高杠杆分界 2.0。
ELASTIC_RATIO_MIN = 2.0

#: 判断③：产能周转率分位 < 此值 → 低位（供给端可能已出清）。
#: 依据：招商策略「固定资产周转率分位 <= 30%」为出清确认口径，此处放宽到 40。
POSITION_LOW_PCT = 40.0

#: 判断③：产能周转率分位 > 此值 → 高位。40~60 之间不出标签（中间地带没信息）。
POSITION_HIGH_PCT = 60.0

#: 判断② 可靠性：近 8 季营收增速中位数绝对值 < 此值 → 比值不可信，标 unstable。
#: 依据：工程经验。营收长期不动时分母趋零，比值会爆炸。
REV_MEDIAN_STABLE_MIN = 3.0

#: 判断② 可靠性（第二条）：近 8 季里「营业利润跨零」的季度占比 > 此值 → 标 unstable。
#: 为什么需要：DOL 在盈亏平衡点趋于无穷，跨零季度的比值不是"弹性"而是噪声。
#: 实测 904 个逐季对里 135 个（15%）跨零；按股票算，46 只（41%）至少有一季跨零。
#: 选 1/3 而不是 1/4：跨零占比 ≥1/3 的 25 只（22%），它们的比值中位数已被
#: 明显带偏（如红日药业 5 季里 3 季跨零、中位 5.30）。再放宽会把只是偶尔
#: 擦到零的公司也一概标不稳定，反而丢掉信息。
ELASTIC_ZERO_CROSS_MAX = 0.3333

#: 判断③ 产能方向：近 CAPACITY_TREND_QUARTERS 季「固定资产+在建工程」增长 >= 此值
#: 且营收未下滑 → 标「扩产中」。
#: 为什么要有这个标记：产能周转率低可能是「需求崩塌（真出清）」也可能是
#: 「大举扩产（分母变大）」，两者语义完全相反，但都显示成「低位」。
#: 实测 49 只低位股里 9 只（18%）属于后者 —— 营收在涨、资产涨得更快。
#: 15% 是拍出来的：低于它更像是正常资本开支而非扩张周期。
CAPACITY_EXPAND_GROWTH = 15.0

#: 判断③ 产能方向：近 CAPACITY_TREND_QUARTERS 季资产增长 <= 此值 → 标「产能在退」。
#: 为什么用负数：重资产企业的固定资产逐年折旧，持平就已经意味着要持续投入
#: 才能维持，资产小幅下降就是净退出。
CAPACITY_SHRINK_GROWTH = -5.0

