#:
#: 这个值**不是**命令行 --out-dir 的默认值：那个参数已经删掉了（见 cycle_report
#: 模块文档）。产物位置只由 `_out_dir_for()` 算，保证可预测。
DEFAULT_OUT_DIR = os.path.join(HUB_ROOT, "output", "cycle-elastic")

#: 报告文件名中的固定片段：<公司名>-<代码>-周期弹性初筛-<时间戳>.html
REPORT_NAME_TAG = "周期弹性初筛"

#: 本地股票名称映射表（--refresh-names 生成）
STOCK_NAMES_CSV = os.path.join(PROJECT_ROOT, "data", "stock_names.csv")

#: 取数节流：每次调用之间至少间隔的毫秒数（跨线程共享闸门）
CALL_INTERVAL_MS = 1600

#: 服务限频时，单次重试至少等这么久（秒）。
#:
#: 为什么单列：限频和普通抖动需要的退避时间差一个数量级。
#: 实测把重试间隔压到 5 秒后，5 只连续限频的股票 2 次重试全部失败，
#: 一直到整批结束都没恢复；改成 60 秒则全部成功。
#: 服务端限频窗口是分钟级的，等短了等于没等。
#: 普通即时错误（超时、空表、结构抖动）不受此限制，用 CLI 的 --retry-wait。
RATE_LIMIT_WAIT = 60

#: 重试退避的随机抖动上限（秒）。**批量并发场景必需**。
#:
#: batch 默认 4 线程，限频会同时打中多个线程；若退避是确定的 60 秒，
#: 它们会同时睡、同时醒、同时再打，把限频窗口原样复现一遍——
#: 2026-11-13 实测：113 只批量在第 19 只起连续 FAIL，重试也救不回来，
#: 就是这个惊群效应。抖动把各线程的唤醒时刻错开。
RETRY_JITTER = 15.0

#: node 子进程的 maxBuffer。data_finance(num=44, fields=all) 单只可达 280KB+，
#: 默认 1MB 在多表齐全时会截断并抛 "stdout maxBuffer exceeded"。
NODE_MAX_BUFFER = 64 * 1024 * 1024

