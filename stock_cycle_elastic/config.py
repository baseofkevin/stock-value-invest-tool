WAVE_WINDOW_QUARTERS = 20

#: 判断② 比值中位数的窗口
ELASTIC_WINDOW_QUARTERS = 8

#: 判断③ 分位的窗口 = 10 年
POSITION_WINDOW_QUARTERS = 40

#: 判断③ 产能方向的观察窗口（8 季 = 2 年）。看两年而不是一年，
